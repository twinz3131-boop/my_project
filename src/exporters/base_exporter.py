"""
Базовый интерфейс экспортёров.

Определяет контракт: у любого экспортёра есть метод
export(records, path), который сохраняет список записей
в файл. Наследники реализуют конкретный формат.

Такая абстракция позволяет:
  * легко добавлять новые форматы (XLSX, SQL, YAML);
  * писать общий код (например, CLI), не привязываясь
    к конкретному формату;
  * тестировать экспортёры через единый интерфейс.
"""
from abc import ABC, abstractmethod
from pathlib import Path


class BaseExporter(ABC):
    """
    Абстрактный экспортёр записей.

    Атрибут extension задаёт расширение файла, которое
    может использовать CLI (например, дописывать его,
    если пользователь не указал).
    """

    # Расширение файла без точки (по умолчанию — пусто,
    # наследники задают своё).
    extension: str = ""

    @abstractmethod
    def export(self, records: list[dict], path: str | Path) -> Path:
        """
        Сохраняет записи в файл path.

        Аргументы:
            records: список словарей — записей для сохранения.
                     Может быть пустым — тогда создастся
                     пустой файл нужного формата.
            path:    путь к итоговому файлу. Если родительской
                     папки не существует — она будет создана.

        Возвращает:
            Path к записанному файлу (удобно для логирования).

        Наследники обязаны реализовать этот метод.
        """
        raise NotImplementedError

    def _ensure_parent(self, path: Path) -> None:
        """
        Создаёт родительские папки, если их нет.

        Вынесено в базовый класс, чтобы каждый наследник
        не дублировал логику mkdir. Идемпотентно —
        повторный вызов безопасен.
        """
        path.parent.mkdir(parents=True, exist_ok=True)